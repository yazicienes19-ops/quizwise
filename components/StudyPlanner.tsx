function toDateStr(d: Date): string {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

function buildMonthCells(
  year: number, month: number, examTerms: ExamTerm[], events: StudyEvent[],
  recurringSessions: RecurringStudySession[], calendarSessions: CalendarStudySession[], collections: Collection[]
): MonthCell[] {
  const firstDay = new Date(year, month, 1);
  const lastDay = new Date(year, month + 1, 0);

  const startDate = new Date(firstDay);
  const dow = startDate.getDay();
  startDate.setDate(startDate.getDate() - (dow === 0 ? 6 : dow - 1));

  const endDate = new Date(lastDay);
  const endDow = endDate.getDay();
  if (endDow !== 0) endDate.setDate(endDate.getDate() + (7 - endDow));

  const cells: MonthCell[] = [];
  const cur = new Date(startDate);

  while (cur <= endDate) {
    const dateStr = toDateStr(cur);
    const daySessions = sessionsForDate(cur, recurringSessions, calendarSessions, collections);
    const items: CalendarItem[] = [
      ...examTerms.filter(e => e.date === dateStr).map(e => ({ id: e.id, title: e.title, source: 'exam' as const })),
      ...events.filter(ev => ev.date === dateStr).map(ev => ({ id: ev.id, title: ev.title, source: 'event' as const, isAuto: !!ev.isAutoGenerated })),
      ...daySessions.map(s => ({ id: s.id, title: s.topic || s.subjectLabel, source: 'session' as const, color: s.color, recurring: s.recurring, startTime: s.startTime })),
    ];
    cells.push({ date: new Date(cur), isCurrentMonth: cur.getMonth() === month, items });
    cur.setDate(cur.getDate() + 1);
  }

  return cells;
}

