type ViewMode = 'monat' | 'liste';

interface CalendarItem {
  id: string;
  title: string;
  source: 'exam' | 'event' | 'session';
  isAuto?: boolean;
  color?: string;
  recurring?: boolean;
  startTime?: string;
}

interface MonthCell {
  date: Date;
  isCurrentMonth: boolean;
  items: CalendarItem[];
}

